"""Plan generation: the LLM fills a Pydantic plan; it never writes SQL.

- draft_ingest(): maps the columns of an extracted file table (header + the first
  rows only, as untrusted data) to an IngestDraft. The rows themselves are NOT
  generated by the model; the backend takes them from the extracted file.
- draft_plan(): create_table / insert_rows / update_rows / delete_rows from the
  user's message (+ the target table's description when it exists).
Both accept `previous` + `error` for the repair loop.
"""
from __future__ import annotations

import json
from typing import Any

from pydantic import BaseModel

from app.ai.dbops.llm import ChatModel
from app.ai.dbops.prompts import (
    ALLOWED_TYPES,
    INGEST_SYSTEM,
    KIND_RULES,
    PLAN_SYSTEM,
    REPAIR_SUFFIX,
    file_block,
    render,
)
from app.schemas.plans import (
    AnyPlan,
    CreateTablePlan,
    DeleteRowsPlan,
    IngestDraft,
    InsertRowsPlan,
    Intent,
    UpdateRowsPlan,
)

PLAN_MODELS: dict[Intent, type[BaseModel]] = {
    Intent.create_table: CreateTablePlan,
    Intent.insert_rows: InsertRowsPlan,
    Intent.update_rows: UpdateRowsPlan,
    Intent.delete_rows: DeleteRowsPlan,
}


def _repair(previous: BaseModel | dict[str, Any] | None, error: str | None) -> str:
    if previous is None or not error:
        return ""
    data = previous.model_dump(mode="json", by_alias=True) if isinstance(previous, BaseModel) \
        else previous
    if isinstance(data, dict) and isinstance(data.get("rows"), list) and len(data["rows"]) > 5:
        data = {**data, "rows": [*data["rows"][:5], ["...more rows omitted..."]]}
    return render(REPAIR_SUFFIX, PLAN=json.dumps(data, default=str)[:6000], ERROR=error[:1000])


def _target_line(schema: str | None, table: str | None) -> str:
    return f"Target from the user's request: schema={schema or '?'}, table={table or '?'}."


async def draft_ingest(
    message: str,
    *,
    chat_model: ChatModel,
    schema: str | None,
    table: str | None,
    file_tables: list[dict[str, Any]],
    raw_excerpt: str = "",
    previous: BaseModel | dict[str, Any] | None = None,
    error: str | None = None,
) -> IngestDraft:
    system = render(INGEST_SYSTEM, TYPES=ALLOWED_TYPES) + _repair(previous, error)
    user = (
        f"User request:\n{message.strip()[:4000]}\n\n{_target_line(schema, table)}\n\n"
        "Extracted tables (untrusted data, header + first rows only):\n"
        + file_block(file_tables, raw_excerpt=raw_excerpt[:1500])
    )
    return await chat_model.with_structured_output(IngestDraft).ainvoke(
        [("system", system), ("user", user)]
    )


async def draft_plan(
    intent: Intent,
    message: str,
    *,
    chat_model: ChatModel,
    schema: str | None,
    table: str | None,
    table_description: str | None = None,
    previous: BaseModel | dict[str, Any] | None = None,
    error: str | None = None,
) -> AnyPlan:
    model = PLAN_MODELS[intent]
    system = render(PLAN_SYSTEM, KIND=intent.value, KIND_RULES=KIND_RULES[intent.value],
                    TYPES=ALLOWED_TYPES) + _repair(previous, error)
    context = (f"Current definition of the target table:\n{table_description}"
               if table_description else "The target table does not exist yet.")
    user = (f"User request:\n{message.strip()[:4000]}\n\n{_target_line(schema, table)}\n\n"
            f"{context}")
    plan = await chat_model.with_structured_output(model).ainvoke(
        [("system", system), ("user", user)]
    )
    return plan  # type: ignore[return-value]
